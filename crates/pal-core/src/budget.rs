/// 파생 사슬을 몇 마디까지 따라가는가.
///
/// # 자리표시다 — **어느 측정도 이 값을 정하지 않았다**
///
/// [DESIGN §12.4](../../../docs/DESIGN.md) 의 예산 표에 **`미측정` 으로** 서 있다
/// (2026-08-13). 같은 표의 *브리핑 도달 깊이 3홉* 에서 자릿수만 빌렸고 근거는 그것뿐이다.
/// §15-40 이 이미 *"낡음 전파의 비용이 미측정"* 을 열린 채로 적어 두었다 — 그 값을
/// 정하는 것은 **F11 · F17** 의 실측이다.
///
/// **옛 자리**: `pal_core::cascade`.
pub const PROVISIONAL_CASCADE_DEPTH: usize = 3;

/// 후보 집합 상한 `K` — [DESIGN §12.4](../../../docs/DESIGN.md) 의 예산 표. 초기값 32.
///
/// # ⚠ 이것이 「흩어진 자리」 목록에 없었다
///
/// 옛 `budget.rs` 의 목록은 넷을 적었고 이 상수는 거기 없다. **그런데 이것이야말로
/// 예산 표의 `K` 이고**, F05 §5.2 의 `Budget::candidate_set_max` 가 가리키는 바로
/// 그 값이다. 목록이 자기가 세는 것을 빠뜨린 자리이고, 그 사실이 *"사람이 세면 다음에
/// 늘어난 것이 빠진다"* 의 실물 사례다.
///
/// **이름에 `PROVISIONAL_` 이 없다.** 값이 미측정인데 접두어가 없으므로 §5.5 의 명명
/// 규율을 어기고 있다 — **여기서 고치지 않는다.** 이름을 바꾸는 것은 `doctor` 의 위반
/// 문장과 시험을 함께 움직이고, 그것은 이 조각의 합격선이 아니다. **발견은 게이트에
/// 적고 넘긴다**(`docs/gates/F05.md`).
///
/// **옛 자리**: `pal_core::doctor`.
pub const CANDIDATE_LIMIT: usize = 32;

/// 표본 한 검사가 보는 단위 수의 기본값.
///
/// **자리표시다** — §12.4 의 예산 표에 `미측정` 으로 서 있다(2026-08-13). 값을 정하는
/// 것은 **F05** 의 예산 회귀이고, `[f22.4]` 가 선 것은 *"기본이 표본이고 전수가 명시적
/// 호출"* 이라는 §12.7 의 분기가 **존재하는가**까지다.
///
/// **옛 자리**: `pal_core::doctor`.
pub const PROVISIONAL_SAMPLE_MAX: usize = 512;

/// 파일 크기 상한의 기본값 — stack §5.5 의 자리표시 2MB.
///
/// **실측에서 나온 숫자가 아니다.** 번들·미니파이 파일이 파서를 멈추는 것을 막는
/// 값이고, 넘은 파일은 조용히 사라지지 않고 `Excluded{oversize}` 로 적힌다.
///
/// **옛 자리**: `pal_extract::classify`.
pub const OVERSIZE_BYTES: usize = 2 * 1024 * 1024;

/// 생성물 표식을 찾을 파일 머리의 길이.
///
/// **예산이다** — *"얼마까지 보고 멈추는가"*. 넘어가면 그 뒤의 `@generated` 는 안 보이고,
/// 그 파일은 `Generated` 가 아니라 보통 파일로 분류된다. **자리표시다.**
///
/// **옛 자리**: `pal_extract::classify`.
pub const MARKER_SCAN_BYTES: usize = 2048;

/// 셔뱅을 볼 파일 머리의 길이. 첫 줄이면 충분하다.
///
/// **옛 자리**: `pal_extract::recognize`.
pub const SHEBANG_SCAN_BYTES: usize = 256;

/// 이력을 얼마나 거슬러 올라가는가. **예산이고, 걸리면 그 사실이 산출에 남는다.**
///
/// 값은 자리표시다(stack §5.5) — 어느 측정도 이 숫자를 정하지 않았고, DESIGN §12.4 의
/// 예산 표에 `미측정` 으로 서 있다(2026-08-13). 재는 것은 **F05** 의 예산 회귀다.
/// 걸린 것과 정말 없는 것을 `NotFoundReason::HistoryBudget` 이 구별한다.
///
/// **옛 자리**: `pal_cli::defect` — 그리고 **비공개였다.** 비공개 예산은 밖에서 셀 수
/// 없고, 셀 수 없는 예산은 목록에 안 오른다.
pub const PROVISIONAL_HISTORY_BUDGET: usize = 400;

/// 1층 캐시의 기본 예산 — F04 §3.4 의 **2GiB**.
///
/// **자리표시다.** 어느 측정도 이 숫자를 정하지 않았다([DESIGN §5.5] 계열).
/// 넘겨서 줄이는 것은 `pal cache prune --budget` 이고, 확정은 예산 회귀(F05)의 것이다.
///
/// **옛 자리**: `pal_cli::cache` — **F04 가 더했다.** 옛 목록이 적힌 뒤에 늘어난 자리다.
