//! 예산 상수 — [stack §5.5](../../../docs/plan/00-stack.md).
//!
//! > **단일 위치** — 전부 `pal-core::budget` 의 상수. 다른 곳에 리터럴로 나타나면 CI 실패
//! > **초기값은 자리표시** — 각 상수에 *"어느 기능의 어느 측정이 확정하는가"* 를 주석으로
//! > 단다. 확정 전 값은 `PROVISIONAL_` 접두어
//!
//! # 이 모듈이 §5.5 를 만족시킨 자리다 — **그리고 흩어져 있던 것이 넷이 아니라 여섯이었다**
//!
//! 옛 판의 이 주석은 *"여기 있는 것은 하나이고 흩어진 나머지가 넷"* 이라 적고 목록을
//! 두었다. `[f02.2]` 가 *"옮기는 것은 이 조각의 합격선이 아니다"* 로 **F05 에 배정했고**
//! ([`docs/gates/F02-2-partial.md`]), 여기가 그 만기다(`[f05.1.pass]` ①).
//!
//! **목록을 적어 둔 뒤 둘이 더 늘었다.** F04 가 `DEFAULT_BUDGET_BYTES` 를 더했고
//! `EXTRACT_CHUNK` 는 애초에 목록에 없었다 — **자리를 세는 목록도 낡는다**는 것이
//! 이 이동이 남긴 사실이고, 그래서 목록이 아니라 **`cargo xtask check` 의 「예산 상수
//! 단일 위치」** 가 이 규율을 진다. 사람이 세면 다음에 늘어난 것이 빠진다.
//!
//! # 여기 있는 것과 여기 없는 것
//!
//! 있는 것은 **예산** — *"얼마까지 보고 멈추는가"* 를 정하는 값이다.
//! 없는 것은 **정체성·형식의 상수** — `ZSTD_LEVEL`(압축 수준) · 캐시 키의 층 표시 ·
//! 문법 rev 는 예산이 아니라 **산출을 정하는 입력**이고, 그것들은 [ADR-0004] 가
//! 캐시 키의 성분으로 요구하는 자리에 산다. 둘을 한 곳에 모으면 *"이 값을 바꾸면
//! 느려진다"* 와 *"이 값을 바꾸면 답이 달라진다"* 가 같은 파일에서 같아 보인다.
//!
//! [ADR-0004]: ../../../docs/adr/0004-cache-key-covers-every-input-that-decides-the-output.md
//! [`docs/gates/F02-2-partial.md`]: ../../../docs/gates/F02-2-partial.md

/// `ERROR` 가 삼킨 바이트가 이 백분율을 **넘으면** 파일을 `Partial` 이 아니라
/// `Unsupported{GrammarDefeated}` 로 낮춘다 (옛 F02 §3.4 · `[f02.2.pass]` ④).
///
/// # 자리표시다 — **어느 측정도 이 값을 정하지 않았다**
///
/// [옛 DESIGN §5.5] 가 명시했다: *"이 숫자들 중 실측에서 나온 것은 하나도 없다."*
/// 확정은 예산 회귀(**F05**)의 것이다.
///
/// # 이 코퍼스에서 이 값이 무엇을 갈랐는가 (2026-08-13)
///
/// `portal-backend @ a29cad0bf6a8` 의 `partial` **30 건**에 대 본 결과다:
///
/// | | 건수 | 그 파일들이 낸 선언 |
/// |---|---:|---:|
/// | 30% 초과 — 강등된다 | **27** | **1** |
/// | 30% 이하 — `Partial` 로 남는다 | 3 | 3 |
///
/// 강등되는 27 중 **26 이 선언을 하나도 못 낸다.** 그것들이 `partial`(*"일부는 읽었다"*)로
/// 적혀 있었고 **그 문장이 거짓이었다** — 읽은 것이 없다. 임계가 가른 것이 정확히
/// *"부분 결과가 있다"* 와 *"문법이 이 파일을 통째로 못 읽었다"* 다.
///
/// **그렇다고 30 이 실측값이 되는 것은 아니다.** 이 코퍼스에서 걸린 값의 분포는
/// 0% · 43% · 68% · 79% · 82% · 100% 이고 **30 과 43 사이에 아무것도 없다.** 40 이나
/// 20 을 넣어도 같은 27 건이 갈린다 — 그러므로 이 관측은 임계를 **확정하지 않는다.**
/// 그 사실이 이 상수가 `PROVISIONAL_` 인 이유다.
///
/// [옛 DESIGN §5.5]: ../../../docs/plan/00-stack.md
pub const PROVISIONAL_ERROR_RATIO_PERCENT: usize = 30;

