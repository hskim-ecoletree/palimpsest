/// `touch` 한 답이 싣는 결박의 상한 — **[옛 F11 §3.3] 의 「상위 N(기본 10)」.**
///
/// # 왜 이것이 예산인가
///
/// *"얼마까지 보고 멈추는가"* 다. [R-11](../../../docs/plan/00-risks.md#r-11)이 이 값의
/// 이유를 적었다 — *"지식 베이스를 아무리 잘 만들어도 통째로 밀어 넣으면 쓸모를
/// 잃는다."* **자른 나머지는 [`crate::ElisionReason::BindingMaxExceeded`] 로 실린다.**
///
/// # ⚠ 낡은 것은 이 상한에 안 걸린다
///
/// [옛 F11 §3.3] 이 못 박았다 — *"`stale` 은 상한에 걸려도 우선 포함. 낡은 것이 안 보이면
/// 이 기능의 존재 이유가 사라진다."* **그래서 이 상수는 「싣는 수의 상한」이 아니라
/// 「낡지 않은 것을 싣는 수의 상한」이다**, 그리고 그 비대칭이 이 제품의 요구다.
///
/// # 자리표시다 — **어느 측정도 이 값을 정하지 않았다**
///
/// [옛 F11 §3.3] 이 *"기본 10"* 이라고 적은 값을 그대로 옮겼고, 그 문서도 근거를 안 적었다.
/// ★ **2026-08-18 — 확정 경로가 사라졌다.** 옛 주석은 *"확정은 **실 MCP 세션**의 응답
/// 토큰 분포(F06 · [R-11] 의 판정)가 한다"* 였는데, MCP 어댑터가 ADR-0025 로 지워지면서
/// **호스트가 실제로 소비한 컨텍스트를 재던 유일한 자리가 없어졌다.** 남은
/// `envelope_two_layer.rs` 는 **자기 정합** 시험이라 이 값을 확정하지 못한다.
/// 그래서 이 상수는 지금 **근거 없는 자리표시**이고, [R-11] 이 그 사실을 적고 있다.
///
/// [옛 F11 §3.3]: ../../../docs/plan/disposal-map.md
pub const PROVISIONAL_TOUCH_BINDING_MAX: usize = 10;

/// 계획 항목의 **경로 패턴**이 맞출 수 있는 파일 수의 상한 — [옛 F12 §4].
