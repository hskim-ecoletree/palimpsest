/// `ERROR` 가 삼킨 바이트가 이 백분율을 **넘으면** 파일을 `Partial` 이 아니라
/// `Unsupported{GrammarDefeated}` 로 낮춘다 (F02 §3.4 · `[f02.2.pass]` ④).
///
/// # 자리표시다 — **어느 측정도 이 값을 정하지 않았다**
///
/// [DESIGN §5.5] 가 명시했다: *"이 숫자들 중 실측에서 나온 것은 하나도 없다."*
/// 확정은 예산 회귀(**F05**)의 것이다.
///
/// # 이 코퍼스에서 이 값이 무엇을 갈랐는가 (2026-08-13)
///
/// `portal-backend @ a29cad0bf6a8` 의 `partial` **30 건**에 대 본 결과다:
///
/// | | 건수 | 그 파일들이 낸 선언 |
/// |---|---:|---:|
/// | 30% 초과 — 강등된다 | **27** | **1** |
/// | 30% 이하 — `Partial` 로 남는다 | 3 | 3 |
///
/// 강등되는 27 중 **26 이 선언을 하나도 못 낸다.** 그것들이 `partial`(*"일부는 읽었다"*)로
/// 적혀 있었고 **그 문장이 거짓이었다** — 읽은 것이 없다. 임계가 가른 것이 정확히
/// *"부분 결과가 있다"* 와 *"문법이 이 파일을 통째로 못 읽었다"* 다.
///
/// **그렇다고 30 이 실측값이 되는 것은 아니다.** 이 코퍼스에서 걸린 값의 분포는
/// 0% · 43% · 68% · 79% · 82% · 100% 이고 **30 과 43 사이에 아무것도 없다.** 40 이나
/// 20 을 넣어도 같은 27 건이 갈린다 — 그러므로 이 관측은 임계를 **확정하지 않는다.**
/// 그 사실이 이 상수가 `PROVISIONAL_` 인 이유다.
///
/// [DESIGN §5.5]: ../../../docs/plan/00-stack.md
pub const PROVISIONAL_ERROR_RATIO_PERCENT: usize = 30;
