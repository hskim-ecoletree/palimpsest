//! **재구축 등가성** — 2층을 통째로 지우고 **1층 + 의도 저장소**로 되세운다. CI 상시.
//!
//! 합격선 정본은 `corpus/criteria.toml` `[f04.pass].rebuild_equivalence` 이고 판정은
//! `docs/gates/F04.md` 다. F04 문서 §6 의 세 조건을 그대로 잰다.
//!
//! # 이 검사의 옛 판이 틀렸었다는 사실이 이 검사의 형태를 정한다
//!
//! F04 문서 §6 이 스스로 적었다 — 이전 판(*"그 외 출처는 복원되지 않는가"*)은
//! **의도 유실을 정상으로 승인하는 검사**였다([R-21]). 그래서 여기서 묻는 것은
//! *"복원되지 않는가"* 가 아니라 **"어느 저장소에서 오는가"** 다:
//!
//!   ① `extracted` 가 전부 복원되는가 — **1층에서 온다**
//!   ② 결박이 전부 복원되는가 — **의도 저장소에서 온다**
//!   ③ 의도 저장소가 **안 변하는가** — 읽기만 했으므로
//!
//! # ⚠ ③ 을 **바이트로** 재지 않는다. 잴 수 없기 때문이고, 그 사실이 발견이다
//!
//! F04 문서 §6 은 ③ 을 *"`intent.*` 파일의 **바이트**가 변하지 않는가"* 로 적었다.
//! **그 조건은 저장 기술의 사실과 부딪힌다** — `redb` 의 `Database::create` 는
//! **열기만 해도 파일을 쓴다.** 이 세션에서 쟀다: 같은 `pal touch` 를 두 번 돌리면
//! 1,056,768 바이트 중 **110 바이트**가 달라지고 길이는 그대로다.
//!
//! 그래서 바이트 불변은 **의도 저장소를 여는 명령에 대해서는 성립할 수 없다.**
//! 성립하는 곳은 **여는 일이 없는 명령** — `pal cache prune` 이고, 그쪽에서는 바이트로
//! 잰다(`prune_boundary.rs`). **R-21 의 진짜 하중이 그쪽이다.**
//!
//! 여기서는 ③ 을 **값의 불변**으로 잰다 — 결박 전부가 조각까지 같은가. 문서의 낱말을
//! 그대로 CI 에 박았으면 그 검사는 **상시 실패했을 것이고, 상시 실패하는 검사는
//! 지워진다.** 그 사실을 `docs/gates/F04.md` §발견 에 1급으로 적었다.
//!
//! # 그리고 ★ 「1층에서 왔는가」를 따로 잰다
//!
//! ①②③ 이 다 참인데 **다시 파싱한 것**일 수 있다. 그러면 이 검사는 캐시가 아니라
//! 추출기의 결정성을 잰 것이다. 그래서 재구축 회차의 **캐시 적중 수**를 함께 본다.
//!
//! [R-21]: ../../../docs/plan/00-risks.md#r-21

mod common;

use common::{저장소, pal};
use pal_store::Projection;

/// 대장 회계에서 적중·빗나감을 꺼낸다. **`--json` 의 `cache` 자리다.**
fn 적중_빗나감(json: &str) -> (u64, u64) {
    let v: serde_json::Value = serde_json::from_str(json).expect("대장 JSON");
    let c = &v["cache"];
    (c["hits"].as_u64().expect("hits"), c["misses"].as_u64().expect("misses"))
}

#[test]
fn 이층을_지워도_일층과_의도로_같은_것이_선다() {
    let repo = 저장소("rebuild");
    let pal_dir = repo.join(".palimpsest");
    let index = pal_dir.join("index.redb");
    let intent = pal_dir.join("intent.redb");

    // ① 채운다 — 1층 · 2층 · 의도층.
    pal(&repo, &["ledger", ".", "--json"]);
    pal(&repo, &["bind", "알파", "--note", "첫째 결박"]);
    pal(&repo, &["bind", "Gamma", "--note", "둘째 결박 — Kotlin 쪽이다"]);

    let 심볼_전 = pal(&repo, &["ledger", ".", "--symbols"]);
    let 만짐_전 = pal(&repo, &["touch", "알파", "--json"]);
    let 감마_전 = pal(&repo, &["touch", "Gamma", "--json"]);
    let 의도_길이_전 = std::fs::metadata(&intent).expect("의도 저장소").len();
    // **자리 목록과 행 수를 실물에서 뜬다** — 이름으로 세지 않는다.
    let (자리_전, 행_전, 엣지_전) = 투영_전수(&index);

    // **하한이다.** 아무것도 안 섰으면 아래 전부가 공짜로 통과한다.
    assert!(심볼_전.lines().count() >= 3, "심볼이 {} 줄뿐이다", 심볼_전.lines().count());
    assert!(index.exists(), "2층이 아예 안 생겼다");
    assert!(만짐_전.contains("첫째 결박"), "결박이 답에 안 실렸다: {만짐_전}");

    // ② **2층을 통째로 지운다.** `pal doctor --rebuild` 가 할 일이고, 여기서는 손으로.
    std::fs::remove_file(&index).expect("2층 삭제");
    assert!(!index.exists());

    // ③ 되세운다 — **1층은 그대로 두었다.**
    let 대장_json = pal(&repo, &["ledger", ".", "--json"]);
    let (적중, 빗나감) = 적중_빗나감(&대장_json);
    let 심볼_후 = pal(&repo, &["ledger", ".", "--symbols"]);
    let 만짐_후 = pal(&repo, &["touch", "알파", "--json"]);
    let 감마_후 = pal(&repo, &["touch", "Gamma", "--json"]);
    let (자리_후, 행_후, 엣지_후) = 투영_전수(&index);

    // ①의 판정 — `extracted` 가 전부 복원됐는가. **바이트로 같아야 한다.**
    assert_eq!(심볼_후, 심볼_전, "2층을 지웠더니 추출 산출이 달라졌다");

    // ②의 판정 — 결박이 전부 복원됐는가.
    assert!(만짐_후.contains("첫째 결박"), "2층을 지웠더니 결박이 사라졌다: {만짐_후}");
    assert_eq!(만짐_후, 만짐_전, "같은 질문에 다른 답이 나왔다");

    // ③의 판정 — 의도 저장소의 **값**이 안 변했다. 두 결박의 답이 조각까지 같다.
    //
    // 바이트로 재지 않는 이유는 이 파일의 머리 주석이다 — `redb` 는 열기만 해도 쓴다.
    // **크기는 안 변한다**(쟀다), 그래서 그것만은 함께 본다.
    assert!(감마_후.contains("둘째 결박"), "둘째 결박이 사라졌다: {감마_후}");
    assert_eq!(감마_후, 감마_전, "재구축 뒤 결박의 답이 달라졌다 — **R-21**");
    assert_eq!(
        std::fs::metadata(&intent).expect("의도 저장소").len(),
        의도_길이_전,
        "재구축이 의도 저장소를 키우거나 줄였다 — 읽기만 했어야 한다"
    );

    // ── ★ `[f05.2.pass]` ④ — **2층의 모든 자리가 재생되는가. 전수로.** ────────
    //
    // F04 가 세운 이 시험은 **심볼과 결박만** 봤다. 엣지가 생기면 자동으로 안 넓어진다.
    // 그래서 자리 목록을 **코드에 박지 않고 실물에서 뜬다** — 박으면 새 자리가 생겨도
    // 검사가 안 넓어지고, 그것이 이 시험이 한 번 걸린 형태다.
    assert_eq!(자리_후, 자리_전, "2층의 자리 목록이 재구축으로 달라졌다");
    assert_eq!(행_후, 행_전, "2층의 행 수가 재구축으로 달라졌다");
    // **하한이다.** 엣지가 0 이면 「엣지가 같다」가 공짜로 통과한다.
    assert!(엣지_전 >= 1, "엣지가 {엣지_전} 개다 — 이 검사는 엣지를 안 재고 있다");
    assert_eq!(엣지_후, 엣지_전, "재구축 뒤 엣지 수가 달라졌다");

    // ★ 그리고 그것이 **1층에서 왔다.** 다시 파싱했으면 이 줄이 걸린다.
    assert!(적중 > 0, "재구축 회차의 캐시 적중이 0 이다 — 1층이 아니라 재파싱이 답을 냈다");
    assert_eq!(빗나감, 0, "1층이 온전하면 빗나감이 0 이어야 한다 — {빗나감} 건");

    assert!(index.exists(), "2층이 되세워지지 않았다");
    let _ = std::fs::remove_dir_all(&repo);
}

/// 2층의 **자리 목록 · 자리별 행 수 · 엣지 수** — 전수로.
///
/// `[f05.2.pass]` ④: *"이름으로 세지 않고 `list_tables` 로 **전수로** 뜬다. 재생되지
/// 않는 자리가 하나라도 있으면 반증이다."*
fn 투영_전수(index: &std::path::Path) -> (Vec<String>, std::collections::BTreeMap<String, u64>, usize) {
    let p = Projection::open(index).expect("2층");
    (
        p.table_names().expect("자리 목록"),
        p.row_counts().expect("행 수"),
        p.edge_count().expect("엣지 수"),
    )
}
