//! **파일에 손대기 전에 서는 문** — 경로가 아니라 **그 자리의 정체**를 본다.
//!
//! # [`super::inside`] 와 무엇이 다른가
//!
//! `inside` 는 *"이 경로가 대상 안인가"* 를 판정한다. 여기는 *"그 자리가 우리가 다뤄도
//! 되는 종류의 것인가"* 를 판정한다. 둘은 **다른 축**이고, 실측이 그 사실을 정했다:
//!
//! | 형태 | `inside` 가 잡나 | 왜 |
//! |---|---|---|
//! | `.claude → ~/.claude` 심링크 | **잡는다** | `canonicalize` 가 밖이라는 신원을 낸다 |
//! | 대상 안의 파일이 **밖의 파일과 하드링크** | **못 잡는다** | 하드링크에는 「밖」이라는 신원이 **원리상 없다** |
//!
//! 실측: 밖의 `victim.txt` 가 `e3b0c442…`(0바이트)가 됐고 **rc=0** 이었다.
//!
//! # ★ 하드링크 — **세는 축은 유닉스에만 있고, 보증은 양쪽에 있다**
//!
//! 소유자 결정(2026-08-16): *"windows 를 대응한다는 가정하에 앞으로 모든 설계와 개발이
//! 되어야 해."*
//!
//! [`제자리에_써도_되나`] 의 링크 수 세기는 `std::os::unix::fs::MetadataExt::nlink`
//! 위에 서고, **Windows 에는 그 문이 없다** — `number_of_links()` 는 unstable 이고
//! raw FFI 는 `unsafe 금지` 게이트가 막는다.
//!
//! 앞 회차는 여기까지 적고 멈췄다. 그리고 실측(2026-08-16, 일반 사용자 권한)이 그
//! 멈춤의 값을 냈다 — **대상 밖 파일에 우리 블록이 실렸고 rc=0 이었다.** 적어 둔
//! 주석은 아무것도 안 막는다.
//!
//! 그래서 [`제자리를_준비한다`] 가 **다른 축으로 같은 보증**을 세운다: 셀 수 없는
//! 플랫폼에서는 **끊고 쓴다.** 결정의 전문과 안 고른 것 셋은 그 함수의 문서에 있다
//! ([docs/DESIGN.md](../../../../docs/DESIGN.md) §D 하드링크).

use std::path::Path;

use anyhow::{Context, Result, bail};

/// **우리가 읽고 쓰는 자리는 일반 파일이거나 없거나 둘 중 하나다.**
///
/// # 왜 종류를 먼저 묻는가
///
/// `std::fs::read` 는 **여는 순간 매달린다.** writer 없는 FIFO 를 열면 `open(2)` 이
/// 거기서 잠기고, 시간 상한도 취소도 없다. 실측: `.claude/settings.json` 을 FIFO 로
/// 두면 `pal install` 과 `pal doctor` 가 **영원히** 매달렸다.
///
/// `.claude/pal` 이 FIFO 인 경우는 `create_dir_all` 이 이미 막고 있었다 — **같은
/// 규율을 나머지 자리에도 세운다.**
///
/// ⚠ 이 문은 `stat` 이라 안 매달린다. 그리고 [`std::fs::metadata`] 는 심링크를
/// 따라가므로, 「안을 가리키는 심링크」는 그 **대상의 종류**로 판정된다 — 경계는
/// [`super::inside::Root::join`] 이 이미 봤다.
///
/// # Errors
/// 그 자리가 있는데 일반 파일이 아니면.
pub fn 일반_파일이거나_없나(path: &Path) -> Result<()> {
    let Ok(meta) = std::fs::metadata(path) else { return Ok(()) };
    if meta.is_file() {
        return Ok(());
    }
    bail!(
        "{} 가 **일반 파일이 아니다**({}) — 읽지도 쓰지도 않는다.\n    \
         이름 있는 파이프·장치·소켓을 열면 그 자리에서 **매달리고**(실측: 영원히), \
         디렉터리면 우리가 쓸 자리가 아예 없다. 사람이 봐야 한다",
        path.display(),
        종류(&meta)
    );
}

fn 종류(meta: &std::fs::Metadata) -> &'static str {
    if meta.is_dir() {
        return "디렉터리다";
    }
    #[cfg(unix)]
    {
        // ⚠ **유닉스 전용 가정** — `FileTypeExt` 가 가르는 넷은 유닉스의 종류다.
        use std::os::unix::fs::FileTypeExt;
        let t = meta.file_type();
        if t.is_fifo() {
            return "이름 있는 파이프(FIFO)다";
        }
        if t.is_socket() {
            return "소켓이다";
        }
        if t.is_block_device() || t.is_char_device() {
            return "장치 파일이다";
        }
    }
    "일반 파일이 아니다"
}

/// 종류를 먼저 묻고 읽는다. **읽는 자리는 전부 이 문을 지난다.**
///
/// # Errors
/// 일반 파일이 아니거나 못 읽으면.
pub fn 읽는다(path: &Path) -> Result<Vec<u8>> {
    일반_파일이거나_없나(path)?;
    std::fs::read(path).with_context(|| format!("읽지 못했다: {}", path.display()))
}

/// 종류를 먼저 묻고 통째로 쓴다(없으면 만든다).
///
/// # Errors
/// 일반 파일이 아니거나 못 쓰면.
pub fn 쓴다(path: &Path, bytes: &[u8]) -> Result<()> {
    일반_파일이거나_없나(path)?;
    std::fs::write(path, bytes).with_context(|| format!("쓰지 못했다: {}", path.display()))
}

/// **제자리 쓰기를 해도 되는 자리인가.**
///
/// # 무엇을 이기게 했는가
///
/// 제자리 쓰기를 고른 이유는 *"안쪽 심링크·모드·하드링크를 살린다"* 였다
/// ([`super::blocks`] 머리말). 그런데 하드링크를 살리는 것과 **하드링크를 통해 밖이
/// 새는 것**은 같은 동작의 앞뒷면이다 — 링크된 파일에 제자리로 쓰면 그 바이트가
/// 저쪽에도 그대로 간다.
///
/// **밖으로 새는 것을 막는 쪽을 이기게 했다.** 링크 수가 1 이 아니면 고치지 않고
/// 멈춘다. 잃는 것은 *"하드링크된 `CLAUDE.md` 도 편집해 준다"* 이고, 지키는 것은
/// *"어느 경로에서도 대상 바깥을 안 건드린다"*(`[f24]` ⑦)이다. 후자가 게이트의
/// 가장 센 줄이다.
///
/// # Errors
/// 그 자리가 하드링크로 여러 이름을 지고 있으면.
#[cfg_attr(not(unix), expect(clippy::unnecessary_wraps, reason = "unix 밖에서는 셀 수가 없다"))]
pub fn 제자리에_써도_되나(path: &Path) -> Result<()> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        let Ok(meta) = std::fs::metadata(path) else { return Ok(()) };
        if meta.is_file() && meta.nlink() > 1 {
            bail!(
                "{} 에 **하드링크가 걸려 있다**(이름 {}개) — 제자리에서 안 고친다.\n    \
                 하드링크에는 「대상 밖」이라는 신원이 **원리상 없다.** 심링크는 \
                 `canonicalize` 가 풀어 막지만 이것은 못 막는다 — 그래서 여기서 멈춘다.\n    \
                 그 파일의 링크를 끊은 뒤(`cp` 로 복사해 갈아끼우기) 다시 돌리십시오",
                path.display(),
                meta.nlink()
            );
        }
    }
    let _ = path;
    Ok(())
}

/// **쓰기 직전** — 이 자리에 제자리로 써도 대상 밖이 안 새는 상태로 만든다.
///
/// # ★ 세는 것과 끊는 것 — 축이 다르고 보증이 같다 (소유자 결정 2026-08-17)
///
/// [`제자리에_써도_되나`] 는 **묻기만 한다**(1단계 미리보기가 그것을 쓴다). 그런데
/// 그 물음에 답할 수 없는 플랫폼이 있다:
///
/// | | 링크 수를 셀 수 있나 | 그래서 무엇을 하나 |
/// |---|---|---|
/// | 유닉스 | `MetadataExt::nlink` — **된다** | **거부한다.** 사람이 보게 한다 |
/// | Windows | `number_of_links()` 는 **unstable**(`windows_by_handle`)이고, raw FFI 는 `unsafe 금지` 게이트가 막는다 — **안 된다** | **끊고 쓴다** |
///
/// ★ **끊는 것은 임시방편이 아니라 유닉스가 사람에게 시키는 바로 그 일이다** — 유닉스
/// 쪽 거부 문구가 적은 처방이 *"`cp` 로 복사해 갈아끼우기"* 다. 셀 수 없는 플랫폼에서는
/// 그것을 쓰기 경로가 대신 한다.
///
/// **보증은 같다**: `[f24]` ⑦ *"어느 경로에서도 대상 바깥을 안 건드린다"* 가 양쪽에서
/// 선다. **상호작용은 다르다**: 유닉스는 멈추고 묻고, Windows 는 끊고 나아간다.
/// 그 차이의 이유는 하나뿐이다 — **한쪽만 볼 수 있다.**
///
/// # 무엇을 안 골랐는가
///
/// | 후보 | 왜 안 골랐나 |
/// |---|---|
/// | `windows-sys` 를 들여 `GetFileInformationByHandle` 을 부른다 | **`unsafe 금지` 게이트가 원천에서 막는다.** `forbid` 는 국소 `allow` 로 못 뚫고, FFI 호출은 우리 크레이트 안에 `unsafe` 블록을 요구한다. 게이트를 낮추는 값이 이 한 검사보다 크지 않다. stack §3.4(의존 최소)와도 부딪힌다 |
/// | 못 세운다고 선언하고 **설치마다 경고를 낸다** | 정상 설치가 매번 경고를 내면 **사용자가 경고를 무시하는 법을 배운다.** 같은 회차에 `doctor` 검사 4 에서 고친 것이 정확히 그 형태다 |
/// | 유닉스도 끊는 쪽으로 통일한다 | 유닉스는 **볼 수 있다.** 볼 수 있는 곳에서 사람에게 안 묻는 것은 정보를 버리는 것이고, 제자리 쓰기가 지키던 모드·안쪽 심링크도 함께 잃는다 |
///
/// # ⚠ 잃는 것을 적어 둔다
///
/// 이 경로는 파일을 **새로 만들어 갈아끼우므로**, Windows 에서 그 파일에 **명시적으로
/// 걸린 ACL 은 사라진다**(부모에서 상속되는 것은 새 파일에도 다시 붙는다). 그리고
/// 사용자가 대상 **안**에 걸어 둔 하드링크도 끊긴다 — 우리가 그것을 볼 수 없기 때문이다.
/// **그 값이 ⑦ 보다 크지 않다**: ⑦ 은 이 게이트의 가장 센 줄이고, 나머지는 속성이다.
///
/// # Errors
/// 유닉스에서 하드링크가 걸려 있으면. 그리고 어느 쪽이든 끊는 데 실패하면.
pub fn 제자리를_준비한다(path: &Path) -> Result<()> {
    제자리에_써도_되나(path)?;
    #[cfg(windows)]
    {
        링크를_끊는다(path)?;
    }
    Ok(())
}

/// 이 자리를 **이름 하나짜리 새 파일**로 갈아끼운다 — 내용은 그대로.
///
/// 임시 파일을 **같은 디렉터리에** 만들고 `rename` 으로 덮는다. 순서가 이것이어야 한다:
/// 실패해도 원본이 그대로 남는다. 지우고 다시 만드는 쪽은 중간에 실패하면 **사용자
/// 파일이 사라진다.**
///
/// `rename` 이 바꾸는 것은 **디렉터리 항목 하나**다. 밖에 걸린 다른 이름은 옛 파일을
/// 계속 가리키므로 **그 내용이 안 바뀐다** — 그것이 여기서 얻는 전부다.
#[cfg(windows)]
fn 링크를_끊는다(path: &Path) -> Result<()> {
    let Ok(meta) = std::fs::metadata(path) else { return Ok(()) };
    if !meta.is_file() {
        return Ok(());
    }
    let 내용 = 읽는다(path)?;

    // 이름 뒤에 붙인다 — `with_extension` 은 `CLAUDE.md` 의 `.md` 를 먹는다.
    let mut 임시 = path.as_os_str().to_owned();
    임시.push(".pal-relink");
    let 임시 = std::path::PathBuf::from(임시);

    std::fs::write(&임시, &내용)
        .with_context(|| format!("링크를 끊을 임시 파일을 못 만들었다: {}", 임시.display()))?;
    if let Err(e) = std::fs::rename(&임시, path) {
        // **원본은 그대로다.** 임시만 걷어내고 사람에게 넘긴다 — 잔해를 남기지 않는다.
        let _ = std::fs::remove_file(&임시);
        return Err(anyhow::Error::new(e).context(format!(
            "{} 의 하드링크를 끊지 못했다 — 이 플랫폼은 링크 수를 셀 수 없어서 \
             끊고 쓰는 것이 대상 밖을 지키는 길이다. 끊지 못하면 안 쓴다",
            path.display()
        )));
    }
    Ok(())
}
