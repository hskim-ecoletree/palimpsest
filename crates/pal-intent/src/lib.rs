//! 의도 저장소 — 결박·`asserted` 라벨·관측 원문·승인/거부 이력의 **원본**.
//!
//! # 이 크레이트에는 지우는 API 가 없다
//!
//! 없는 것이 대응이다([R-21](../../../docs/plan/00-risks.md)). 2층에 의도가 살면
//! *"지우고 재구축"* 이 사람의 노동을 지우는 명령이 되고, **재구축 등가성 검사는
//! 그 상태에서도 통과하므로 검사가 유실을 정상으로 승인하게 된다.**
//!
//! | | 1층 | 2층 | 의도 저장소 |
//! |---|---|---|---|
//! | 원본은 어디 | git | 1층 + 의도 저장소 | **자기 자신** |
//! | 지워도 되나 | 예 (재파싱) | 예 (재구축) | **아니오 — 유실** |
//!
//! # S3 시점의 상태
//!
//! **처음으로 내용이 들어왔다.** [`IntentStore`] 가 결박을 담고, 그것이 이 크레이트가
//! 존재한 이유를 처음으로 시험한다 — S2 까지는 빈 방에 자물쇠를 건 상태였다.
//!
//! **여전히 지우는 API 가 없다.** 승인·관측 원문은 F12·F16 이 채운다.
//!
//! # F05 가 더한 둘
//!
//! **JSONL 내보내기/읽기** — 이 저장소만 지는 부담이다(옛 F05 §2 의 넷째). 2층은 지우고
//! 다시 만들면 되므로 스키마 버전도 백업도 필요 없지만 **여기는 재구축 불가**다.
//!
//! **읽기 전용 열기** — `redb::Database::create` 는 열기만 해도 파일을 쓴다(F04 가
//! 110 바이트를 쟀다). 읽는 명령은 [`IntentStore::open_read_only`] 로 온다.
//!
//! **읽기는 여전히 더하기이지 바꿔치기가 아니다** — 파일에 없는 결박은 그대로 남는다.
//! 지우는 API 가 없다는 대응이 이 명령에서도 참이어야 한다.

#![forbid(unsafe_code)]

mod store;

pub use store::{
    ImportReport, IntentError, IntentLine, IntentStore, JSONL_SCHEMA_VERSION,
};

