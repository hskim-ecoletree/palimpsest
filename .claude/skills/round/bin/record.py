def 검증(줄번호, obj, out, 파일=None, 버전=SCHEMA_VERSION, 종류_="레코드"):
    """한 줄을 잰다. 문제를 `out` 에 담는다.

    ★ **파일 이름을 함께 낸다.** `xtask` 가 이 함수의 출력을 그대로 실어 나르는데,
    앞 판은 `4행: …` 만 내서 **회차가 둘 이상이면 어느 파일의 4 행인지 알 수 없었다**
    (독립 리뷰 3 라운드). 위임하면서 잃은 좌표를 되찾는다.
    """
    앞 = f"{파일}:" if 파일 else ""
    아는_필드 = 필드들(버전)
    # ★ **예외표는 레코드가 아니다.** (정정 2026-08-23 · 독립 리뷰 R1)
    #   `disposal-overrides.jsonl` 은 **덮어쓸 칸만** 적는 자리라 `REQUIRED` 를
    #   원리상 못 채운다. 앞 판은 `종류` 를 **버전 해석에만** 쓰고 행 검증은 언제나
    #   레코드 자로 재서, 예외표를 `check` 에 넘기면 필수 필드 없음이 쏟아졌다.
    #   `xtask` 는 `종류=레코드` 만 넘기므로 **CI 는 초록이었고 아무도 안 봤다.**
    if 종류_ == "예외표":
        if not obj.get("id"):
            out.append(f"{앞}{줄번호}행: 예외표 행에 `id` 가 없다 — 무엇을 덮어쓰는지가 없다")
        if len(obj) < 2:
            out.append(f"{앞}{줄번호}행: 예외표 행에 덮어쓸 칸이 없다 — `id` 뿐이다")
    else:
        for k in REQUIRED:
            if k not in obj or obj[k] in (None, ""):
                out.append(f"{앞}{줄번호}행: 필수 필드 `{k}` 가 없다")
    for k, vals in ENUM.items():
        if k in obj and obj[k] is not None and obj[k] not in vals:
            out.append(f"{앞}{줄번호}행: `{k}` 값 `{obj[k]}` 는 enum 밖이다 ({' · '.join(vals)})")
    for k in obj:
        if k not in 아는_필드:
            out.append(
                f"{앞}{줄번호}행: 모르는 필드 `{k}`"
                + (f" — 이 파일은 스키마 {버전} 이고 `{k}` 는 그 뒤에 생겼다" if k in FIELDS else "")
            )
    # ★ **열림 축은 버전 3 부터다.** 옛 파일에는 원리상 없다.
    if 종류_ == "레코드" and 버전 >= 3:
        if obj.get("상태") is None:
            out.append(f"{앞}{줄번호}행: 필수 필드 `상태` 가 없다 (열림 · 닫힘)")
        elif obj["상태"] == "닫힘" and not obj.get("닫은커밋"):
            out.append(
                f"{앞}{줄번호}행: `닫힘` 인데 `닫은커밋` 이 없다 — "
                "**시점 없는 닫힘은 주장이지 기록이 아니다**"
            )
        elif obj["상태"] == "열림" and obj.get("닫은커밋"):
            out.append(f"{앞}{줄번호}행: `열림` 인데 `닫은커밋` 이 있다 — 둘 중 하나가 거짓이다")
    if obj.get("라운드") is not None and not isinstance(obj["라운드"], int):
        out.append(f"{앞}{줄번호}행: `라운드` 는 정수여야 한다")
    # 대응표가 금지하는 조합
    if obj.get("처분") == "전환" and obj.get("승격됨") == "아니오":
        out.append(f"{앞}{줄번호}행: `전환` 은 항상 승격이다 (대응표)")
    if obj.get("조건변경") == "완화" and obj.get("처분") != "축소":
        out.append(f"{앞}{줄번호}행: `완화` 는 `축소` 로 적는다 (대응표) — 위장한 정정을 가린다")


def 읽기(path):
    """머리 줄과 본문을 가른다."""
    머리, 행 = None, []
    with open(path, encoding="utf-8") as f:
        for i, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            obj = json.loads(line)
            if i == 1 and "schema_version" in obj:
                머리 = obj
            else:
                행.append((i, obj))
    return 머리, 행


def cmd_check(paths):
    문제 = []
    총 = 0
    for p in paths:
        # ★ 받은 경로를 그대로 쓴다 — `relpath` 는 cwd 에 의존해서 부르는 자리에
        #   따라 `../../../../tmp/…` 같은 것이 나온다(실측 2026-08-19).
        상대 = p
        if not os.path.exists(p):
            문제.append(f"{p}: 없다")
            continue
        try:
            머리, 행 = 읽기(p)
        except json.JSONDecodeError as e:
            문제.append(f"{p}: JSON 이 아니다 — {e}")
            continue
        종류_ = (머리 or {}).get("종류", "레코드")
        최신 = SCHEMA_VERSIONS.get(종류_, SCHEMA_VERSION)
        버전 = (머리 or {}).get("schema_version")
        꼬리 = ""
        if 머리 is None:
            문제.append(f"{p}: 머리 줄에 `schema_version` 이 없다")
            버전 = 최신
        elif not isinstance(버전, int):
            문제.append(f"{p}: schema_version 이 정수가 아니다 ({버전!r})")
            버전 = 최신
        elif 버전 > 최신:
            # 앞선 버전은 **모르는 것**이다 — 재는 자가 그 형식을 모른다.
            문제.append(
                f"{p}: schema_version {버전} 는 이 파서가 아는 것({최신})보다 앞선다 — "
                "재는 자가 그 형식을 모른다"
            )
        elif 버전 < 최신:
            # ★ **옛 버전은 「형식 이전」이고 실패가 아니다.** 소급 이주를 안 하기로
            #   했으므로(승격 2), 여기서 실패로 내면 검사가 이주를 강요한다.
            #   ⚠ **다만 침묵하지 않는다** — 「안 잰 축이 있다」를 판정에 실어 낸다.
            꼬리 = f"  ← **형식 이전** (스키마 {버전} · 최신 {최신} · 열림 축을 안 잰다)"
        for 번호, obj in 행:
            검증(번호, obj, 문제, 상대, 버전, 종류_)
        총 += len(행)
        print(f"{p}: {len(행)}행{꼬리}")
    if 문제:
        print("\n".join("  ✗ " + m for m in 문제), file=sys.stderr)
        return 1
    print(f"합계 {총}행 · 문제 없음")
    return 0


def cmd_add(회차, 기준커밋):
    path = os.path.join(회차, "findings.jsonl")
    새로 = not os.path.exists(path)
    # ★ **머리 줄 버전을 먼저 본다.** (G7 · 격리 사본에서 재현)
    #   앞 판은 버전이 달라도 rc=0 으로 덧붙였다 — 그러면 한 파일 안에 **형식이 둘인
    #   행**이 섞이고, 그것을 가르는 축이 파일 어디에도 없다.
    if not 새로:
        try:
            머리, _ = 읽기(path)
        except json.JSONDecodeError as e:
            print(f"  ✗ {path}: JSON 이 아니다 — {e}", file=sys.stderr)
            return 1
        종류_ = (머리 or {}).get("종류", "레코드")
        최신 = SCHEMA_VERSIONS.get(종류_, SCHEMA_VERSION)
        if (머리 or {}).get("schema_version") != 최신:
            print(
                f"  ✗ {path}: 머리 줄이 스키마 {(머리 or {}).get('schema_version')} 인데 "
                f"지금 쓰는 것은 {최신} 이다 — 한 파일에 형식 둘을 섞지 않는다. "
                "이주하거나 새 파일을 열어라",
                file=sys.stderr,
            )
            return 1
    if 기준커밋 is None:
        기준커밋 = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                                  capture_output=True, text=True,
                                  encoding="utf-8").stdout.strip() or None
    줄들 = [l for l in sys.stdin.read().split("\n") if l.strip()]
    문제 = []
    파싱 = []
    for i, l in enumerate(줄들, 1):
        obj = json.loads(l)
        for k, v in OPTIONAL_DEFAULT.items():
            obj.setdefault(k, v)
        if obj.get("기준커밋") is None:
            obj["기준커밋"] = 기준커밋
        검증(i, obj, 문제)
        파싱.append(obj)
    if 문제:
        print("\n".join("  ✗ " + m for m in 문제), file=sys.stderr)
        return 1
    with open(path, "a", encoding="utf-8") as f:
        if 새로:
            f.write(json.dumps({"schema_version": SCHEMA_VERSION,
                                "종류": "레코드",
                                "회차": os.path.basename(os.path.normpath(회차))},
                               ensure_ascii=False) + "\n")
        for obj in 파싱:
            f.write(json.dumps({k: obj[k] for k in FIELDS if k in obj},
                               ensure_ascii=False) + "\n")
    print(f"{path}: {len(파싱)}행 추가")
    return 0


def cmd_count(회차):
    path = os.path.join(회차, "findings.jsonl")
    if not os.path.exists(path):
        print("레코드가 없다")
        return 1
    _, 행 = 읽기(path)
    print(f"레코드 {len(행)}행")
    for 축 in ("출처", "모집단", "유효성", "해악도", "처분"):
        표 = {}
        for _, o in 행:
            표[o.get(축)] = 표.get(o.get(축), 0) + 1
        print(f"  {축:6} " + " · ".join(f"{k} {v}" for k, v in sorted(표.items(), key=lambda x: -x[1])))
    return 0


def main(argv):
    if len(argv) < 2 or argv[1] in ("-h", "--help"):
        print(__doc__)
        return 0
    if argv[1] == "--schema":
        print(json.dumps(스키마(), ensure_ascii=False, indent=2))
        return 0
    if argv[1] == "check":
        return cmd_check(argv[2:])
    if argv[1] == "add":
        기준 = None
        args = argv[2:]
        if "--기준커밋" in args:
            i = args.index("--기준커밋")
            기준 = args[i + 1]
            args = args[:i] + args[i + 2:]
        return cmd_add(args[0], 기준)
    if argv[1] == "conditions":
        return cmd_conditions(argv[2])
    if argv[1] == "gate":
        return cmd_gate(argv[2])
    if argv[1] == "count":
        return cmd_count(argv[2])
    print(f"모르는 명령: {argv[1]}", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
