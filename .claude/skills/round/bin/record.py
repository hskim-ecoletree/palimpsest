# ── 완수 조건 파서 — **이 저장소에서 상자를 읽는 유일한 자리** ────────────────
#
# ★ `dashboard.py` 가 이것을 `import` 하고 `xtask` 가 `conditions` 로 **위임**한다.
#   앞 회차가 `종류` 축을 두 벌로 두었다가 C2-b 반증을 맞았다 — 같은 형태를 안 만든다.
#
# ⚠ 실측 2026-08-22 (사전부검 R2·R3, 격리 사본에서 재현):
#   ① `^- \[` 는 **코드펜스 안의 형식 예시와 `## 범위 밖` 의 불릿까지 센다** → `3/4`
#   ② 들여쓴 상자를 못 본다. **열림 쪽만 고치면 분모가 깨진다** → `2/3`
#   그래서 이 파서는 **절을 알고 · 펜스를 알고 · 들여쓰기를 받는다.**

조건절 = "완수 조건"          # 이 절 안의 상자만 조건이다
판정값 = ["통과", "반증", "대조불가", "미측정"]

_상자 = re.compile(r'^(?P<들여>\s*)- \[(?P<표>[ xX])\]\s+(?P<몸>.*)$')
_아이디 = re.compile(r'^\**([A-Z][0-9]+(?:-[a-z])?)\**\s')
_코드스팬 = re.compile(r'`[^`]*`')
_태그 = re.compile(r'·\s*(?P<판정>통과|반증|대조불가|미측정)\s*(?:⟨전사\s*(?P<전사>[0-9]{4}-[0-9]{2}-[0-9]{2})⟩)?\s*$')


def 조건들(본문):
    """`## 완수 조건` 절의 상자를 낸다. 펜스 안과 다른 절은 안 센다.

    낸다: [{"id","상자","판정","전사","줄","원문","형식오류"}]
    **첫 줄 끝의 태그만 읽는다** — 조건 열이 여러 줄에 걸치기 때문이다(실측 90 중 10).
    """
    out, 안, 펜스 = [], False, False
    for i, 줄 in enumerate(본문.splitlines(), 1):
        if 줄.lstrip().startswith("```"):
            펜스 = not 펜스
            continue
        if 펜스:
            continue
        h = re.match(r'^(#+)\s+(.*)$', 줄)
        if h:
            # ⚠ **깊이를 본다.** 조건은 `### A — …` 같은 하위 절에 산다 —
            #   깊이를 안 보면 첫 하위 제목이 절을 덮어써 **조건이 0 개가 된다**
            #   (실측 2026-08-22: 이 파서의 첫 판이 회차 셋 전부에서 0 을 냈다).
            깊이, 제목 = len(h.group(1)), h.group(2).strip()
            if 깊이 <= 2:
                안 = 제목.startswith(조건절)
            continue
        if not 안:
            continue
        m = _상자.match(줄)
        if not m:
            continue
        몸 = m.group("몸")
        # ⚠ **인라인 코드 스팬을 지우고 태그를 찾는다.** 펜스만 보고 백틱을 안 보면
        #   조건이 형식을 **인용**한 것을 태그로 오인한다 — 실측 2026-08-22: 이 파서가
        #   자기를 만든 `intent.md` 에서 거짓 양성 둘을 냈다(B5·H3).
        태그면 = _코드스팬.sub(" ", 몸)
        오류 = []
        mid = _아이디.match(몸)
        if not mid:
            오류.append("ID 가 없다 (`A1` 꼴이 조건 첫 낱말이어야 한다)")
        mt = _태그.search(태그면)
        켜짐 = m.group("표") in "xX"
        if 켜짐 and not mt:
            오류.append("상자가 켜졌는데 판정 태그가 없다 (`· 통과` 꼴)")
        if (not 켜짐) and mt:
            오류.append("상자가 안 켜졌는데 판정 태그가 있다 — 안 켜짐은 미측정이다")
        # ⚠ 순서를 못 박는다: `· <판정> ⟨전사 …⟩`. 뒤집으면 「마지막 `·` 뒤」 규칙이
        #   enum 밖 토큰을 읽어 90 개가 전부 실패한다(사전부검 R2 #13).
        if "⟨전사" in 태그면 and not (mt and mt.group("전사")):
            # ⚠ 매치가 났어도 `전사` 가 비면 **뒤집힌 것**이다 — 정규식이 줄 끝의
            #   `· 통과` 만 보고 앞의 `⟨전사…⟩` 를 조용히 버린다. 등록한 음성 대조가
            #   이 구멍을 찾았다(실측 2026-08-22).
            오류.append("`⟨전사 …⟩` 가 판정 뒤에 안 왔다 (`· <판정> ⟨전사 …⟩`)")
        # ⚠ **같은 ID 가 두 번 오면 형식 오류다.** (독립 리뷰 R6)
        #   게이트 표준 표는 ID 집합이라 중복을 하나로 접고, 계기판 ②는 상자를 **행으로**
        #   센다 — 그래서 복제 줄 하나로 **같은 회차의 두 자리가 다른 분모**를 말한다.
        #   실측: 검사는 `(69개)`, 계기판은 `2 / 70`. 그러고도 21/21 초록이었다.
        if mid and any(c["id"] == mid.group(1) for c in out):
            오류.append(f"조건 ID `{mid.group(1)}` 가 두 번 있다 — ID 는 한 회차에 한 번이다")
        out.append({
            "id": mid.group(1) if mid else None,
            "상자": 켜짐,
            "판정": (mt.group("판정") if mt else ("미측정" if not 켜짐 else None)),
            "전사": (mt.group("전사") if mt else None),
            "줄": i,
            "원문": 줄.rstrip(),
            "형식오류": 오류,
        })
    return out


def cmd_conditions(path):
    본문 = open(path, encoding="utf-8").read()
    cs = 조건들(본문)
    print(json.dumps({
        "파일": path,
        "조건": cs,
        "열림": sum(1 for c in cs if not c["상자"]),
        "닫힘": sum(1 for c in cs if c["상자"]),
        "형식오류": sum(len(c["형식오류"]) for c in cs),
    }, ensure_ascii=False, indent=2))
    return 1 if any(c["형식오류"] for c in cs) else 0


# ── 게이트 표준 표 파서 — **원장 둘 중 나머지 하나** ──────────────────────────
#
# `intent.md` 의 상자가 한 원장이고 `docs/gates/<기능>.md` 의 `## 판정` 이 다른
# 원장이다. 둘이 갈리는 것을 아무도 안 대던 것이 이 회차가 연 금지역이다.
#
# ★ **표준 표는 두 열이고 수 칸이 없다.** 소유자가 잠근 문장:
#   *"수를 안 적고 조건 ID를 적는다. ID를 적으면 수는 세면 나온다. 캐시가 아니다.
#     그리고 대조가 집합 같음이 되어 훨씬 강하다 — 수만 맞고 내용이 다른 경우를 잡는다."*
#
#     | 판정 | 조건 |
#     |---|---|
#     | 통과 | A1 A2 A3 |
#     | 반증 | — |
#     | 대조불가 | C9-a C9-b |
#     | 미측정 | — |
#
#     **검산** — 통과 3 · 반증 0 · 대조불가 2 · 미측정 0 = 5
#
# ⚠ **검산 줄은 표 칸이 아니다.** 규약 §9 가 *"넷의 합이 등록된 조건 수와 같아야
#   한다 — 검산하고 적는다"* 를 요구하므로 수는 한 줄로 적히되, **그 수가 ID 목록
#   길이와 갈리면 형식 오류**다. 게이트에 사전 등록한 음성 대조 ⑤ 가 이것이다.
#
# ⚠ **표준 표가 없는 게이트는 오류가 아니라 「형식 이전」이다.** 옛 게이트를 새
#   형식으로 안 옮기는 것이 `docs/gates/README.md` 의 선례다 — 지난 판정은 그때의
#   기록이라 형식을 바꿔도 새로 재는 것이 없다.

판정절 = "판정"
_표행 = re.compile(r'^\s*\|(?P<몸>.*)\|\s*$')
_구분행 = re.compile(r'^[\s|:-]+$')
_ID꼴 = re.compile(r'^[A-Z][0-9]+(?:-[a-z])?$')
_빈칸말 = {"—", "–", "-", "", "없음", "(없음)", "0"}
_검산 = re.compile(
    r'검산.*?통과\s*(?P<통과>[0-9]+).*?반증\s*(?P<반증>[0-9]+)'
    r'.*?대조불가\s*(?P<대조불가>[0-9]+).*?미측정\s*(?P<미측정>[0-9]+)\s*=\s*(?P<합>[0-9]+)'
)


def _셀들(줄):
    m = _표행.match(줄)
    if not m:
        return None
    return [c.strip() for c in m.group("몸").split("|")]


def _꾸밈없이(s):
    return s.replace("*", "").replace("`", "").strip()


def 게이트판정(본문):
    """게이트 `## 판정` 절의 **표준 표**를 낸다. 없으면 「형식 이전」이다.

    낸다: {"표준표","목록","판정","검산","형식오류"}

    ⚠ **표는 한 덩이다.** 헤더 다음의 **잇닿은** 표 행만 읽는다 — 같은 절에 다른 표가
      있는 게이트가 실재한다(`rust-extractor.md` 의 ⓐ 회차 조건 표 · ⓑ 합격선 표).
      잇닿음을 안 보면 그 행들이 표준 표 안으로 빨려 들어간다.

    ★ **ⓑ 꼴의 합격선 표는 대조 밖이다.** `[rust.pass]` 의 `①`~`⑤` 는 `intent.md` 에
      없는 토큰이라 원장 대조의 모집단이 아니다 — 헤더가 `| 판정 | 조건 |` 가 아니면
      이 파서가 안 읽는 것이 그 경계다.
    """
    안, 펜스 = False, False
    줄들 = []          # 이 절 안의 (원본줄번호, 줄)
    for i, 줄 in enumerate(본문.splitlines(), 1):
        if 줄.lstrip().startswith("```"):
            펜스 = not 펜스
            continue
        if 펜스:
            continue
        h = re.match(r'^(#+)\s+(.*)$', 줄)
        if h:
            # `조건들()` 과 같은 규율 — **깊이를 본다.** `### 「당기는가」` 같은
            # 하위 절이 `## 판정` 을 덮어쓰면 표가 절 밖으로 새어 나간다.
            if len(h.group(1)) <= 2:
                안 = h.group(2).strip().startswith(판정절)
            continue
        if 안:
            줄들.append((i, 줄))

    # ① 헤더 `| 판정 | 조건 |` 를 찾는다. 없으면 **형식 이전**이다 — 오류가 아니다.
    시작 = None
    for k, (_, 줄) in enumerate(줄들):
        셀 = _셀들(줄)
        if 셀 and [_꾸밈없이(c) for c in 셀] == ["판정", "조건"]:
            시작 = k
            break
    if 시작 is None:
        return {"표준표": False, "목록": {}, "판정": {}, "검산": None, "형식오류": []}

    오류, 목록, 판정 = [], {}, {}

    # ② 헤더 뒤의 **잇닿은** 표 행만 이 표의 몸이다.
    k = 시작 + 1
    본문행 = []
    while k < len(줄들):
        줄 = 줄들[k][1]
        셀 = _셀들(줄)
        if 셀 is None:
            break
        if not _구분행.match(줄.replace("|", " ")):
            본문행.append(셀)
        k += 1

    # ③ 넷이 각각 **한 번씩** 와야 한다. 빠지면 그 판정이 조용히 안 세어진다.
    for 셀 in 본문행:
        이름 = _꾸밈없이(셀[0]) if 셀 else ""
        if 이름 not in 판정값:
            오류.append(f"표준 표에 판정 아닌 행이 있다: `{이름}` — 넷은 {판정값} 다")
            continue
        if 이름 in 목록:
            오류.append(f"`{이름}` 행이 두 번 있다 — 한 판정은 한 행이다")
            continue
        if len(셀) < 2:
            오류.append(f"`{이름}` 행에 조건 칸이 없다")
            continue
        if len(셀) > 2:
            오류.append(
                f"`{이름}` 행이 세 칸 이상이다 — 표준 표는 `| 판정 | 조건 |` "
                "두 열이다 (**수 칸 없음**)"
            )
            continue
        ids = []
        for 토막 in re.split(r'[\s·,]+', _꾸밈없이(셀[1])):
            if 토막 in _빈칸말:
                continue
            if not _ID꼴.match(토막):
                오류.append(f"`{이름}` 행의 `{토막}` 이 조건 ID 꼴이 아니다 (`A1` · `C9-a`)")
                continue
            if 토막 in 판정:
                오류.append(f"조건 `{토막}` 이 판정 둘에 있다 (`{판정[토막]}` · `{이름}`)")
                continue
            ids.append(토막)
            판정[토막] = 이름
        목록[이름] = ids
    for 이름 in 판정값:
        if 이름 not in 목록:
            오류.append(f"표준 표에 `{이름}` 행이 없다 — 넷을 다 적어야 합이 선다")
            목록[이름] = []

    # ④ 검산 — **적힌 수와 ID 목록 길이가 갈리면 형식 오류**다 (음성 대조 ⑤).
    #    표 **바로 뒤**에서 찾는다. 절 전체를 훑으면 다른 표의 합계 문장을 집는다.
    검산줄 = None
    for _, 줄 in 줄들[k:k + 6]:
        if "검산" in 줄:
            검산줄 = 줄
            break
    검산 = None
    if 검산줄 is None:
        오류.append(
            "표준 표 바로 뒤에 검산 줄이 없다 — 규약 §9 가 "
            "*\"넷의 합이 등록된 조건 수와 같아야 한다 — 검산하고 적는다\"* 를 요구한다 "
            "(`**검산** — 통과 3 · 반증 0 · 대조불가 2 · 미측정 0 = 5`)"
        )
    else:
        m = _검산.search(검산줄)
        if not m:
            오류.append(
                f"검산 줄을 못 읽었다: {검산줄.strip()} — "
                "`통과 N · 반증 N · 대조불가 N · 미측정 N = N` 순서다"
            )
        else:
            검산 = {k2: int(m.group(k2)) for k2 in 판정값}
            검산["합"] = int(m.group("합"))
            for 이름 in 판정값:
                if 검산[이름] != len(목록[이름]):
                    오류.append(
                        f"검산이 `{이름} {검산[이름]}` 이라 적었는데 ID 목록은 "
                        f"{len(목록[이름])} 개다 — 수는 세면 나온다. 캐시를 두지 않는다"
                    )
            if 검산["합"] != len(판정):
                오류.append(
                    f"검산 합이 {검산['합']} 인데 적힌 ID 는 {len(판정)} 개다"
                )

    return {"표준표": True, "목록": 목록, "판정": 판정, "검산": 검산, "형식오류": 오류}


def cmd_gate(path):
    본문 = open(path, encoding="utf-8").read()
    g = 게이트판정(본문)
    g["파일"] = path
    print(json.dumps(g, ensure_ascii=False, indent=2))
    return 1 if g["형식오류"] else 0


