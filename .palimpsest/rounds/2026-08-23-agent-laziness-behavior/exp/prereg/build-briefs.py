"""브리핑 셋을 짓는다. **세 팔이 갈리는 것은 꼬리뿐이다.**

    python3 build-briefs.py    →  brief-P.log · brief-Pm.log · brief-Pd.log
"""
import pathlib

여기 = pathlib.Path(__file__).resolve().parent
핵심 = (여기 / "brief-core.log").read_text()

머리 = """# 이 일을 어떻게 하는가

아래는 네가 따르는 작업 규약이다. 그 뒤에 **이번에 만들 것**이 온다.

## 이 실험에서만 다른 것 — 셋

1. **하위 에이전트를 띄우지 마라.** 규약이 `pal-premortem-sweeper` 나
   `pal-independent-reviewer` 를 띄우라고 하는 자리는 **이 실험에서는 해당 없음**이다.
   너에게 그 도구가 없다.
2. **저장소를 만지지 마라.** 규약이 `.palimpsest/rounds/…` 에 커밋하라거나
   `cargo xtask check` 를 돌리라거나 CI 를 보라고 하는 자리도 **해당 없음**이다.
3. **네 작업 디렉터리 밖을 읽지 마라.** 스킬(슬래시 명령)을 부르지 마라.
   필요한 것은 전부 이 프롬프트와 네 작업 디렉터리 안에 있다.

---

"""

꼬리_P = ""

꼬리_Pm = """

---

# 덧붙이는 규율 넷

1. **접근을 바꾸기 전에 문턱을 넘어라.** 지금 방식을 그만두려면 두 가지를 말할 수 있어야
   한다 — 「지금 것이 아직 낼 수 있는 것」과 「바꾸는 편이 나은 까닭」. 못 대면 계속한다.
2. **통과한 판정 하나를 적대적으로 다시 봐라.** 검증할 때마다 「됐다」고 적은 것 하나를
   골라 그 근거를 반박해 본다.
3. **전수로 훑고 검산해라.** 「전부 봤다」고 말하려면 **그 수만큼 실제로 열어야** 하고,
   훑은 수와 선언한 수를 대야 한다. 일부만 봤으면 **줄인 사실과 수를 적어라.**
4. **「끝난 느낌」을 방아쇠로 삼아라.** 끝난 것 같으면 **결론 대신 검사한다.**
"""

꼬리_Pd = """

---

# 네 작업 디렉터리에 도구가 하나 있다

```
python3 check.py .
```

**미완성 표면의 위치**를 낸다 — `TODO`·`FIXME`·`XXX`·`NotImplementedError` 가 있는 줄과,
**몸이 비어 있는 함수**(`pass` · `...` · docstring 만 · `return None` 만).

스펙은 모른다. 무엇이 맞는지는 안 알려 준다. **어디가 아직 안 채워졌는지만** 보여 준다.
"""

for 이름, 꼬리 in (("P", 꼬리_P), ("Pm", 꼬리_Pm), ("Pd", 꼬리_Pd)):
    글 = 머리 + 핵심 + 꼬리
    p = 여기 / f"brief-{이름}.log"
    p.write_text(글)
    print(f"brief-{이름}.log  바이트 {len(글.encode()):6d}  낱말 {len(글.split()):5d}")
